// Writes apps/web/.env.local (git-ignored) from a deployed stage's Terraform outputs, e.g.
// `pnpm web:env dev`. An existing SESSION_SECRET is kept so current sessions stay valid.

import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const stage = process.argv[2];
const siteUrl = process.env.SITE_URL ?? (stage === 'dev' ? 'http://localhost:3000' : undefined);
if (!stage || !siteUrl) {
  // Non-dev stages only allow their registered HTTPS origin as a Cognito callback.
  console.error('Usage: [SITE_URL=https://registered.origin] web-env.mjs <stage>');
  process.exit(1);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputs = JSON.parse(
  execFileSync('terraform', ['output', '-json'], {
    cwd: path.join(root, 'infrastructure/terraform/environments', stage),
    encoding: 'utf8',
  }),
);
const target = path.join(root, 'apps/web/.env.local');
const existing = existsSync(target) ? readFileSync(target, 'utf8') : '';
const secret =
  /^SESSION_SECRET=(.{32,})$/m.exec(existing)?.[1] ?? randomBytes(32).toString('base64url');

const lines = [
  '# Generated by scripts/web-env.mjs; do not commit.',
  `NEXT_PUBLIC_SITE_URL=${siteUrl}`,
  `NEXT_PUBLIC_CONTACT_EMAIL=${outputs.contact_email?.value ?? ''}`,
  `RESOLVE_API_URL=${outputs.api_endpoint.value}`,
  `COGNITO_DOMAIN=${outputs.hosted_domain.value}`,
  `COGNITO_CLIENT_ID=${outputs.web_client_id.value}`,
  `SESSION_SECRET=${secret}`,
];
writeFileSync(target, `${lines.join('\n')}\n`, { mode: 0o600 });
console.error(`Wrote ${path.relative(root, target)} for stage ${stage}.`);
